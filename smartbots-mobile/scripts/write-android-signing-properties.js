const fs = require('fs');
const path = require('path');

const gradlePropertiesPath = path.join(__dirname, '..', 'android', 'gradle.properties');
const required = [
  'SMARTBOTS_UPLOAD_STORE_FILE',
  'SMARTBOTS_UPLOAD_STORE_PASSWORD',
  'SMARTBOTS_UPLOAD_KEY_ALIAS',
  'SMARTBOTS_UPLOAD_KEY_PASSWORD',
];

for (const key of required) {
  if (!process.env[key]) {
    console.error(`${key} ausente no ambiente.`);
    process.exit(1);
  }
}

if (!fs.existsSync(gradlePropertiesPath)) {
  console.error('android/gradle.properties não encontrado. Rode expo prebuild antes.');
  process.exit(1);
}

let current = fs.readFileSync(gradlePropertiesPath, 'utf8');
if (!current.endsWith('\n')) current += '\n';

const clean = current
  .split(/\r?\n/)
  .filter((line) => !required.some((key) => line.trim().startsWith(`${key}=`)))
  .join('\n')
  .replace(/\n*$/, '\n');

const addition = [
  '',
  '# SmartBots release signing - generated by GitHub Actions',
  `SMARTBOTS_UPLOAD_STORE_FILE=${process.env.SMARTBOTS_UPLOAD_STORE_FILE}`,
  `SMARTBOTS_UPLOAD_STORE_PASSWORD=${process.env.SMARTBOTS_UPLOAD_STORE_PASSWORD}`,
  `SMARTBOTS_UPLOAD_KEY_ALIAS=${process.env.SMARTBOTS_UPLOAD_KEY_ALIAS}`,
  `SMARTBOTS_UPLOAD_KEY_PASSWORD=${process.env.SMARTBOTS_UPLOAD_KEY_PASSWORD}`,
  '',
].join('\n');

fs.writeFileSync(gradlePropertiesPath, clean + addition);
console.log('android/gradle.properties atualizado com propriedades de assinatura release.');
